#!/usr/bin/env python3
"""Derive the committed P2P oracle inventory and keep the published report honest.

The initial P2P scope's supported-profile report
(docs/reference/p2p-profiles.md) embeds a generated inventory block between
marker comments. This tool renders that block from the same case tables the
launchers execute — the handshake scenario table, the p2p launcher's builder
table, the lifecycle names and the committed wrap fixtures — so the published
matrix can never drift from the corpora the gates actually run. ``--check``
refuses any drift between the committed page and the derived inventory; the
exit codes follow the coverage tool's convention: 0 verified, 1 drift,
2 tooling error.
"""
import argparse
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
import handshake_launch
import p2p_launch
import p2p_lifecycle_corpus
import p2p_wrap

ROOT = Path(__file__).resolve().parents[2]
REPORT = ROOT / 'docs/reference/p2p-profiles.md'
BEGIN = '<!-- inventory: generated by scripts/oracle/profile_report.py; edit only through the case tables it derives from -->'
END = '<!-- end inventory -->'


def p2p_scope():
    """The initial P2P scope's committed corpora as ordered launcher -> case names."""
    return {
        'handshake': list(handshake_launch.scenarios()),
        'p2p': p2p_launch.case_names() + list(p2p_lifecycle_corpus.NAMES),
        'p2p-wrap': list(p2p_wrap.NAMES),
    }


def _wrapped(names, prefix='  '):
    """Case names as comma-joined backticked spans wrapped at a stable width."""
    lines, line = [], ''
    for name in names:
        span = f'`{name}`'
        if line and len(line) + len(span) + 2 > 96:
            lines.append(prefix + line)
            line = ''
        line += (', ' if line else '') + span
    if line:
        lines.append(prefix + line)
    return lines


def render():
    """The inventory block exactly as the committed report must embed it."""
    scope = p2p_scope()
    total = sum(len(names) for names in scope.values())
    lines = [BEGIN, '',
             f'Committed inventory: {total} cases across {len(scope)} launchers, derived from the case tables the '
             'launchers execute at the pinned revision.',
             '']
    for launcher, names in scope.items():
        lines.append(f'- `{launcher}` — {len(names)} cases:')
        lines.extend(_wrapped(names))
        lines.append('')
    lines.append(END)
    return lines


def check(path):
    """None when the committed block equals the derived inventory, else the drift."""
    try:
        text = path.read_text(encoding='utf-8')
    except OSError as error:
        return f'profile report unreadable: {error}'
    begin, end = text.find(BEGIN), text.find(END)
    if begin < 0 or end < 0 or end < begin:
        return 'profile report markers missing: ' + str(path)
    committed = text[begin:end + len(END)].splitlines()
    derived = render()
    if committed == derived:
        return None
    differences = [f'- line {index + 1}: committed `{committed[index]}` vs derived `{derived[index]}`'
                   for index in range(min(len(committed), len(derived)))
                   if committed[index] != derived[index]]
    if len(committed) != len(derived):
        differences.append(f'- line count: committed {len(committed)} vs derived {len(derived)}')
    return ('profile report inventory drift; regenerate with '
            '`python3 scripts/oracle/profile_report.py --write docs/reference/p2p-profiles.md`\n'
            + '\n'.join(differences[:5]))


def write(path):
    """Replace the block between the markers, leaving the rest of the page untouched."""
    text = path.read_text(encoding='utf-8')
    begin, end = text.find(BEGIN), text.find(END)
    if begin < 0 or end < 0 or end < begin:
        raise ValueError('profile report markers missing: ' + str(path))
    path.write_text(text[:begin] + '\n'.join(render()) + text[end + len(END):], encoding='utf-8')


def main():
    parser = argparse.ArgumentParser(description='derive the published P2P profile report inventory')
    parser.add_argument('--check', type=Path, help='verify a committed report instead of printing the block')
    parser.add_argument('--write', type=Path, help='regenerate the block inside a committed report')
    args = parser.parse_args()
    if args.check is not None and args.write is not None:
        parser.error('--check and --write are exclusive')
    if args.check is not None:
        problem = check(args.check)
        if problem is not None:
            print(problem, file=sys.stderr)
            return 1
        print(f'profile report inventory verified: {sum(len(names) for names in p2p_scope().values())} cases')
        return 0
    if args.write is not None:
        write(args.write)
        return 0
    print('\n'.join(render()))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
