"""Shared paths, constants, and scope helpers for the .llm harness tooling.

Everything in this module is stdlib-only and deterministic. The harness
contract: `.llm/` is the single source of truth; every agent front-end file
is a thin pointer into it; nothing exceeds a 300-line hard cap.
"""

from __future__ import annotations

from pathlib import Path

# --- Limits -----------------------------------------------------------------
MAX_LINES = 300  # hard limit; exceeding this is an error
SOFT_WARN_LINES = 270  # advisory threshold (only shown with --verbose)
THIN_POINTER_MAX_LINES = 50  # front-end pointer files must stay thin

# --- Skill metadata ----------------------------------------------------------
CATEGORIES = ("core", "performance", "feature")

# --- Canonical locations -----------------------------------------------------
REPO_ROOT = Path(__file__).resolve().parents[2]
LLM_DIR = REPO_ROOT / ".llm"
SKILLS_DIR = LLM_DIR / "skills"
CONTEXT_PATH = LLM_DIR / "context.md"
INDEX_PATH = SKILLS_DIR / "index.md"

# Files generated by tooling; never authored by hand and excluded from the
# size scan (they grow with the skill count).
GENERATED_RELATIVE = (".llm/skills/index.md",)

# Front-end pointer files: relative path -> exact delegation link that must
# appear in the file. Mirrors the discovery rules of each vendor.
POINTER_FILES = {
    "AGENTS.md": "./.llm/context.md",  # Codex, OpenCode, Cursor, Gemini CLI, ...
    "CLAUDE.md": "./.llm/context.md",  # Claude Code
    ".github/copilot-instructions.md": "../.llm/context.md",  # GitHub Copilot
    ".cursor/rules/llm-context.mdc": "../../.llm/context.md",  # Cursor
    ".windsurf/rules/llm-context.md": "../../.llm/context.md",  # Windsurf
    ".clinerules/llm-context.md": "../../.llm/context.md",  # Cline
}

# Generated agent-skill discovery stub roots (Agent Skills standard).
STUB_ROOTS = (".claude/skills", ".agents/skills")

# Machine-local, never-committed directories (see .gitignore). Links into them
# resolve on the authoring machine but are absent from any fresh checkout, so
# they must not be reported as broken by the link check.
LOCAL_ONLY_DIRS = ("progress",)


def resolve_root(root: Path | None = None) -> Path:
    return Path(root) if root is not None else REPO_ROOT


def size_scope_files(root: Path | None = None) -> list[Path]:
    """Every markdown file the 300-line contract applies to.

    Includes: `.llm/**/*.md` (minus generated files), all pointer files,
    and generated agent stubs. Only files that exist on disk are returned;
    missing pointer files are the instruction linter's job to report.
    """
    base = resolve_root(root)
    files: list[Path] = []

    llm_dir = base / ".llm"
    if llm_dir.is_dir():
        for path in sorted(llm_dir.rglob("*.md")):
            rel = path.relative_to(base).as_posix()
            if rel in GENERATED_RELATIVE:
                continue
            files.append(path)

    for rel in POINTER_FILES:
        path = base / rel
        if path.is_file():
            files.append(path)

    for stub_root in STUB_ROOTS:
        stub_dir = base / stub_root
        if stub_dir.is_dir():
            files.extend(sorted(stub_dir.glob("*/SKILL.md")))

    return files
