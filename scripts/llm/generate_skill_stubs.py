"""Generate Agent Skills discovery stubs for Claude Code (.claude/skills) and
the vendor-neutral location (.agents/skills).

Each stub is a thin pointer to the canonical skill in `.llm/skills/<name>/`,
mirroring the harness philosophy: front-end files are thin wrappers around
canonical content. Stubs are deterministic; CI verifies freshness with
`--check`. Regenerate with `make llm-index`.
"""

from __future__ import annotations

import argparse
import sys
from dataclasses import dataclass, field
from pathlib import Path

_SCRIPTS_DIR = Path(__file__).resolve().parents[1]
if str(_SCRIPTS_DIR) not in sys.path:
    sys.path.insert(0, str(_SCRIPTS_DIR))

from llm import llm_frontmatter  # noqa: E402
from llm import llm_paths  # noqa: E402

GENERATED_BY = (
    "<!-- Generated by scripts/llm/generate_skill_stubs.py; DO NOT EDIT. -->"
    "<!-- Regenerate: make llm-index -->"
)


@dataclass
class StubPlan:
    # desired path -> desired file content
    writes: dict[Path, str] = field(default_factory=dict)
    # stub dirs with no canonical skill backing them
    orphans: list[Path] = field(default_factory=list)


def canonical_skills(root: Path | None = None) -> tuple[dict[str, str], list[str]]:
    """Return ({skill name -> description}, errors)."""
    base = llm_paths.resolve_root(root)
    skills: dict[str, str] = {}
    errors: list[str] = []
    for skill_dir in llm_frontmatter.iter_skill_dirs(base / ".llm" / "skills"):
        problems = llm_frontmatter.validate_skill_dir(skill_dir)
        if problems:
            errors.extend(problems)
            continue
        meta, _ = llm_frontmatter.parse_frontmatter(
            (skill_dir / "SKILL.md").read_text(encoding="utf-8")
        )
        skills[skill_dir.name] = str(meta["description"])
    return skills, errors


def render_stub(name: str, description: str) -> str:
    title = " ".join(part.capitalize() for part in name.split("-"))
    escaped = description.replace("\\", "\\\\").replace('"', '\\"')
    return (
        "---\n"
        f"name: {name}\n"
        f'description: "{escaped}"\n'
        "---\n"
        "\n"
        f"# {title}\n"
        "\n"
        "Read and follow the canonical skill: "
        f"[`{name}`](../../../.llm/skills/{name}/SKILL.md).\n"
        "\n"
        f"{GENERATED_BY}\n"
    )


def plan(root: Path | None = None) -> StubPlan:
    base = llm_paths.resolve_root(root)
    skills, _errors = canonical_skills(base)
    result = StubPlan()

    for name, description in sorted(skills.items()):
        content = render_stub(name, description)
        for stub_root in llm_paths.STUB_ROOTS:
            result.writes[base / stub_root / name / "SKILL.md"] = content

    for stub_root in llm_paths.STUB_ROOTS:
        stub_base = base / stub_root
        if not stub_base.is_dir():
            continue
        for entry in sorted(stub_base.iterdir()):
            if entry.is_dir() and entry.name not in skills:
                result.orphans.append(entry)

    return result


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("root", nargs="?", default=None)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--write", action="store_true")
    parser.add_argument(
        "--prune",
        action="store_true",
        help="With --write, delete orphaned stub directories.",
    )
    args = parser.parse_args(argv)

    root = Path(args.root) if args.root else None
    _skills, errors = canonical_skills(root)
    for error in errors:
        print(f"[llm-stubs] ERROR: {error}", file=sys.stderr)
    if errors:
        return 1

    stub_plan = plan(root)
    base = llm_paths.resolve_root(root)

    if args.write:
        for path, content in sorted(stub_plan.writes.items()):
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content.encode("utf-8"))
        print(f"[llm-stubs] wrote {len(stub_plan.writes)} stub(s)")
        if args.prune:
            import shutil

            for orphan in stub_plan.orphans:
                shutil.rmtree(orphan)
                print(f"[llm-stubs] pruned orphan {orphan}")
        return 0

    # --check (default when --write is absent)
    failures: list[str] = []
    for path, content in sorted(stub_plan.writes.items()):
        if not path.is_file():
            failures.append(f"missing stub: {path.relative_to(base)}")
        elif path.read_bytes() != content.encode("utf-8"):
            failures.append(f"stale stub: {path.relative_to(base)}")
    for orphan in stub_plan.orphans:
        failures.append(
            f"orphan stub (no canonical skill): "
            f"{orphan.relative_to(base)} - run: make llm-index -- --prune"
        )
    for failure in failures:
        print(f"[llm-stubs] ERROR: {failure}", file=sys.stderr)
    if failures:
        print(
            f"[llm-stubs] {len(failures)} problem(s); regenerate: make llm-index",
            file=sys.stderr,
        )
        return 1
    print("[llm-stubs] OK: stubs fresh")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
