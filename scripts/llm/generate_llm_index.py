"""Generate `.llm/skills/index.md` from skill frontmatter (deterministic).

The index groups skills by `metadata.category` (core / performance / feature),
sorted ordinally by name, written as UTF-8 with LF endings and no BOM.
Regenerate with `make llm-index`; CI verifies freshness with `--check`.
"""

from __future__ import annotations

import argparse
import sys
from dataclasses import dataclass
from pathlib import Path

_SCRIPTS_DIR = Path(__file__).resolve().parents[1]
if str(_SCRIPTS_DIR) not in sys.path:
    sys.path.insert(0, str(_SCRIPTS_DIR))

from llm import llm_frontmatter  # noqa: E402
from llm import llm_paths  # noqa: E402

BANNER = (
    "<!-- DO NOT EDIT - generated by scripts/llm/generate_llm_index.py. -->\n"
    "<!-- Regenerate: make llm-index -->\n"
)

SECTION_TITLES = {
    "core": "## Core Skills (Always Consider)",
    "performance": "## Performance Skills",
    "feature": "## Feature Skills",
}


@dataclass(frozen=True)
class SkillMeta:
    name: str
    description: str
    category: str


def collect_skills(
    root: Path | None = None,
) -> tuple[list[SkillMeta], list[str]]:
    base = llm_paths.resolve_root(root)
    skills_dir = base / ".llm" / "skills"
    skills: list[SkillMeta] = []
    errors: list[str] = []

    for skill_dir in llm_frontmatter.iter_skill_dirs(skills_dir):
        problems = llm_frontmatter.validate_skill_dir(skill_dir)
        if problems:
            errors.extend(problems)
            continue
        meta, _ = llm_frontmatter.parse_frontmatter(
            (skill_dir / "SKILL.md").read_text(encoding="utf-8")
        )
        metadata = meta.get("metadata") or {}
        category = (
            metadata.get("category", "feature")
            if isinstance(metadata, dict)
            else "feature"
        )
        skills.append(
            SkillMeta(
                name=skill_dir.name,
                description=str(meta["description"]),
                category=str(category),
            )
        )

    skills.sort(key=lambda s: s.name)
    return skills, errors


def render_index(skills: list[SkillMeta]) -> str:
    lines: list[str] = [
        BANNER.rstrip("\n"),
        "",
        "# Skills Index",
        "",
        "Invoke these skills for specific tasks. Only `name` and `description`",
        "are visible before activation; every body stays under the 300-line cap.",
        "",
    ]
    for category in llm_paths.CATEGORIES:
        group = [s for s in skills if s.category == category]
        if not group:
            continue
        lines.append(SECTION_TITLES[category])
        lines.append("")
        lines.append("| Skill | When to Use |")
        lines.append("| --- | --- |")
        for skill in group:
            lines.append(
                f"| [`{skill.name}`](./{skill.name}/SKILL.md) "
                f"| {skill.description} |"
            )
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def build_index(root: Path | None = None) -> tuple[str, list[str]]:
    skills, errors = collect_skills(root)
    return render_index(skills), errors


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("root", nargs="?", default=None)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args(argv)

    root = Path(args.root) if args.root else None
    text, errors = build_index(root)
    for error in errors:
        print(f"[llm-index] ERROR: {error}", file=sys.stderr)
    if errors:
        return 1

    base = llm_paths.resolve_root(root)
    index_path = base / ".llm" / "skills" / "index.md"

    if args.write:
        index_path.parent.mkdir(parents=True, exist_ok=True)
        index_path.write_bytes(text.encode("utf-8"))
        print(f"[llm-index] wrote {index_path}")
        return 0

    if args.check:
        if not index_path.is_file():
            print(
                f"[llm-index] ERROR: {index_path} is missing; "
                f"run: make llm-index",
                file=sys.stderr,
            )
            return 1
        current = index_path.read_bytes()
        if current != text.encode("utf-8"):
            print(
                f"[llm-index] ERROR: {index_path} is stale; "
                f"run: make llm-index",
                file=sys.stderr,
            )
            return 1
        print("[llm-index] OK: index is fresh")
        return 0

    # No flags: print the generated text.
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
