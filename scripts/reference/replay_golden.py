#!/usr/bin/env python3
"""Build the replay format golden with Python struct, independently of the GDScript encoder."""

import argparse
import hashlib
import json
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DESTINATION = ROOT / 'tests/fixtures/replay/golden.json'
CHECKSUM_A = bytes(range(0x10, 0x20))
CHECKSUM_B = bytes(range(0xf0, 0x100))
NEUTRAL = bytes([0x00, 0x80])
# (inputs for both players, flag, checksum): flag 1 carries a checksum, flag 2 marks a neutral substitute.
FRAMES = [
    (bytes([0x01, 0x02, 0x03, 0x04]), 1, CHECKSUM_A),
    (bytes([0xff, 0x00, 0x7f, 0x80]), 0, b''),
    (NEUTRAL * 2, 2, b''),
    (bytes([0x05, 0x06, 0x07, 0x08]), 1, CHECKSUM_B),
]
FIELDS = {
    'player_count': 2,
    'input_width': 2,
    'frame_count': 4,
    'skipped_frames': 1,
    'input_delay': 258,
    'max_prediction_frames': 8,
    'sync_test': False,
    'neutral_input': NEUTRAL.hex(),
    'engine_version': '4.7.2.stable ed1daf0bf001b61586d9930840f2f1394092c079',
    'addon_version': '0.1.0',
    'upstream_revision': 'fortress-rollback f13cd5c0f2815926785a395947e18da0dbea0dd8',
    'game_seed': '18446744073709551615',
    'game_version': 'golden fixture ~!',
}
NAMES = ['engine_version', 'addon_version', 'upstream_revision', 'game_seed', 'game_version']


def text(value):
    data = value.encode('ascii')
    assert len(data) <= 128 and all(0x20 <= byte <= 0x7e for byte in data)
    return struct.pack('<B', len(data)) + data


def digest(row):
    """The first 16 bytes of the row's SHA-256, the digest that covers one input row."""
    return hashlib.sha256(row).digest()[:16]


def header(version):
    """The 23-byte fixed header: magic, version, roster, width, frame count, skipped, delay, window, sync."""
    packed = b'FRRP' + struct.pack('<HBIIIHBB', version, FIELDS['player_count'], FIELDS['input_width'],
                                   FIELDS['frame_count'], FIELDS['skipped_frames'], FIELDS['input_delay'],
                                   FIELDS['max_prediction_frames'], int(FIELDS['sync_test']))
    assert len(packed) == 23
    return packed


def v5():
    """Status-aware layout: one status per player, covered by the row digest."""
    statuses = [bytes([1, 1]), bytes([1, 3]), bytes([1, 1]), bytes([3, 3])]
    body = b''.join(row + status + struct.pack('<B', flag) + checksum + digest(row + status)
                    for (row, flag, checksum), status in zip(FRAMES, statuses))
    return header(5) + NEUTRAL + b''.join(text(FIELDS[name]) for name in NAMES) + body


def v6():
    """Version five rows plus an exact terminal checksum; skipped rows are forbidden."""
    data = bytearray(v5())
    struct.pack_into('<H', data, 4, 6)
    struct.pack_into('<I', data, 15, 0)
    cursor = 23 + len(NEUTRAL) + sum(1 + len(FIELDS[name]) for name in NAMES)
    for row, flag, checksum in FRAMES:
        if flag == 2:
            data[cursor + len(row) + 2] = 0
        cursor += len(row) + 2 + 1 + len(checksum) + 16
    return bytes(data) + CHECKSUM_A


def v4():
    """The legacy byte-only layout: every frame carries the digest of its own input row."""
    body = b''.join(row + struct.pack('<B', flag) + checksum + digest(row) for row, flag, checksum in FRAMES)
    return header(4) + NEUTRAL + b''.join(text(FIELDS[name]) for name in NAMES) + body


def v3():
    """The released version 3 layout, kept only to prove explicit UNSUPPORTED_VERSION rejection."""
    body = b''.join(row + struct.pack('<B', flag) + checksum for row, flag, checksum in FRAMES)
    return header(3) + NEUTRAL + b''.join(text(FIELDS[name]) for name in NAMES) + body + digest(FRAMES[-1][0])


def v2():
    """The released version 2 layout, kept only to prove explicit UNSUPPORTED_VERSION rejection."""
    body = b''.join(row + struct.pack('<B', flag) + checksum for row, flag, checksum in FRAMES)
    return header(2) + NEUTRAL + b''.join(text(FIELDS[name]) for name in NAMES) + body


def v1():
    """The unreleased session-027 layout: magic, version, players, width, frames, skipped, then rows with 0/1 flags."""
    packed = b'FRRP' + struct.pack('<HBIII', 1, 2, 2, 2, 0)
    return packed + FRAMES[0][0] + b'\x01' + CHECKSUM_A + FRAMES[1][0] + b'\x00'


def chunks(data):
    """Hex in 64-byte lines; readers join them."""
    return [data[start:start + 64].hex() for start in range(0, len(data), 64)]


def fixture():
    return {
        'provenance': [
            'Generated by scripts/reference/replay_golden.py with Python struct little-endian packing.',
            'Layout: docs/integration.md#replay-file-format; upstream replay semantics: fortress f13cd5c0f2815926785a395947e18da0dbea0dd8.',
            'v1 is the unreleased session-027 layout, kept only to prove explicit UNSUPPORTED_VERSION rejection.',
            'v2 is the released layout without the final input digest, kept only to prove explicit UNSUPPORTED_VERSION rejection.',
            'v3 is the released layout that anchors only the final input row, kept only to prove explicit UNSUPPORTED_VERSION rejection.',
        ],
        'v6': chunks(v6()),
        'terminal_checksum': CHECKSUM_A.hex(),
        'v5': chunks(v5()),
        'statuses': [[1, 1], [1, 3], [1, 1], [3, 3]],
        'v4': chunks(v4()),
        'fields': FIELDS,
        'checksums': {'0': CHECKSUM_A.hex(), '3': CHECKSUM_B.hex()},
        'v3': chunks(v3()),
        'v2': chunks(v2()),
        'v1': chunks(v1()),
    }


def rendered():
    return (json.dumps(fixture(), indent=2) + '\n').encode()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true', help='replace the checked-in golden')
    args = parser.parse_args()
    if args.write:
        DESTINATION.parent.mkdir(parents=True, exist_ok=True)
        DESTINATION.write_bytes(rendered())
    elif DESTINATION.read_bytes() != rendered():
        raise ValueError('replay golden differs from the independent generator; investigate before updating')
    print('Replay golden: exact match with the independent generator.')


if __name__ == '__main__':
    main()
