"""Self-tests for the agent discovery stub generator (.claude/skills + .agents/skills)."""

import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from llm import generate_skill_stubs as stubs


def write_canonical_skill(root: Path, name: str, description: str) -> None:
    skill_dir = root / ".llm" / "skills" / name
    skill_dir.mkdir(parents=True, exist_ok=True)
    (skill_dir / "SKILL.md").write_text(
        "---\n"
        f"name: {name}\n"
        f'description: "{description}"\n'
        "metadata:\n"
        "  category: core\n"
        "---\n\n"
        f"# {name}\n\nBody.\n",
        encoding="utf-8",
    )


class PlanTest(unittest.TestCase):
    def setUp(self):
        import tempfile

        self._tmp = tempfile.TemporaryDirectory()
        self.root = Path(self._tmp.name)

    def tearDown(self):
        self._tmp.cleanup()

    def test_every_canonical_skill_plans_a_stub_in_both_roots(self):
        write_canonical_skill(self.root, "my-skill", "Does my thing.")
        plan = stubs.plan(self.root)
        targets = sorted(str(p.relative_to(self.root)) for p in plan.writes)
        self.assertEqual(
            targets,
            [
                ".agents/skills/my-skill/SKILL.md",
                ".claude/skills/my-skill/SKILL.md",
            ],
        )

    def test_orphan_stub_dirs_are_detected(self):
        write_canonical_skill(self.root, "real-skill", "Real.")
        orphan = self.root / ".claude" / "skills" / "ghost-skill"
        orphan.mkdir(parents=True)
        (orphan / "SKILL.md").write_text("stale\n", encoding="utf-8")
        plan = stubs.plan(self.root)
        self.assertEqual([p.name for p in plan.orphans], ["ghost-skill"])


class RenderStubTest(unittest.TestCase):
    def test_stub_has_valid_frontmatter_and_canonical_link(self):
        text = stubs.render_stub("my-skill", 'Description with "quotes".')
        self.assertIn('name: my-skill', text)
        self.assertIn("../../../.llm/skills/my-skill/SKILL.md", text)
        self.assertIn("Generated by", text)
        self.assertNotIn("\r", text)

    def test_deterministic(self):
        self.assertEqual(
            stubs.render_stub("a", "d"), stubs.render_stub("a", "d")
        )


class CheckModeTest(unittest.TestCase):
    def setUp(self):
        import tempfile

        self._tmp = tempfile.TemporaryDirectory()
        self.root = Path(self._tmp.name)

    def tearDown(self):
        self._tmp.cleanup()

    def test_write_then_check_is_green(self):
        write_canonical_skill(self.root, "some-skill", "Some skill.")
        self.assertEqual(stubs.main([str(self.root), "--write"]), 0)
        self.assertEqual(stubs.main([str(self.root), "--check"]), 0)

    def test_check_fails_when_stub_missing(self):
        write_canonical_skill(self.root, "some-skill", "Some skill.")
        self.assertEqual(stubs.main([str(self.root), "--check"]), 1)

    def test_check_fails_when_stub_stale(self):
        write_canonical_skill(self.root, "some-skill", "Some skill.")
        stubs.main([str(self.root), "--write"])
        write_canonical_skill(self.root, "some-skill", "Changed description.")
        self.assertEqual(stubs.main([str(self.root), "--check"]), 1)

    def test_check_fails_on_orphan(self):
        write_canonical_skill(self.root, "some-skill", "Some skill.")
        stubs.main([str(self.root), "--write"])
        orphan = self.root / ".agents" / "skills" / "old-skill"
        orphan.mkdir(parents=True)
        (orphan / "SKILL.md").write_text("stale\n", encoding="utf-8")
        self.assertEqual(stubs.main([str(self.root), "--check"]), 1)


if __name__ == "__main__":
    unittest.main()
